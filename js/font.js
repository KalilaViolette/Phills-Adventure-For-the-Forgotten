const FONT_H = 9, FONT_BASE = 7, FONT_GAP = 1;   // rows per line of glyphs, where the baseline sits, space between letters
const fontSheets = {};                            // one tinted copy of the glyphs per color
function fontSheet(col) {
  if (fontSheets[col]) return fontSheets[col];
  const keys = Object.keys(GLYPHS), at = {};
  let x = 0;
  for (const k of keys) { at[k] = x; x += GLYPHS[k][1].length + 1; }
  const c = document.createElement('canvas'); c.width = x; c.height = FONT_H;
  const g = c.getContext('2d'); g.fillStyle = col;
  for (const k of keys) {
    const [top, ...rows] = GLYPHS[k];
    rows.forEach((row, y) => { for (let i = 0; i < row.length; i++) if (row[i] === '#') g.fillRect(at[k] + i, top + y, 1, 1); });
  }
  return (fontSheets[col] = { c, at });
}
const glyphW = ch => GLYPHS[ch] ? GLYPHS[ch][1].length : null;
function readWidth(text) {
  let w = 0;
  for (const ch of text) { const gw = glyphW(ch); w += (gw ?? Math.ceil(ctx.measureText(ch).width)) + FONT_GAP; }
  return Math.max(0, w - FONT_GAP);
}
// draws text with its baseline at y, like fillText. shadow: a darker copy one pixel down and right first
function readText(text, x, y, col, shadow) {
  x = Math.round(x); y = Math.round(y);
  if (shadow) drawRead(text, x + 1, y + 1, shadow);
  drawRead(text, x, y, col);
}
function drawRead(text, x, y, col) {
  const sh = fontSheet(col);
  for (const ch of text) {
    const gw = glyphW(ch);
    if (gw == null) { ctx.fillStyle = col; ctx.fillText(ch, x, y); x += Math.ceil(ctx.measureText(ch).width) + FONT_GAP; continue; }
    ctx.drawImage(sh.c, sh.at[ch], 0, gw, FONT_H, x, y - FONT_BASE, gw, FONT_H);
    x += gw + FONT_GAP;
  }
}
function wrapRead(text, w) {
  const words = text.split(' '), out = []; let cur = '';
  for (const wd of words) { const tryS = cur ? cur + ' ' + wd : wd; if (readWidth(tryS) > w && cur) { out.push(cur); cur = wd; } else cur = tryS; }
  if (cur) out.push(cur);
  return out;
}
